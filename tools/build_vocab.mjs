// Builds the list of structures the 3D model really has, for the report explainer.
// Left/right copies of a part share one name ("Supraspinatus"); the side is chosen separately.
// Usage: node tools/build_vocab.mjs   (after public/models/index.json and groups.json exist)
import fs from 'node:fs';

const index = JSON.parse(fs.readFileSync('public/models/index.json', 'utf8'));
const groups = JSON.parse(fs.readFileSync('public/models/groups.json', 'utf8'));
const SIDE = /\b(left|right)\b\s*/i;

const entries = []; // [name, side or '', ids]
for (const [id, p] of Object.entries(index.parts)) entries.push([p.name, [id]]);
for (const [name, ids] of Object.entries(groups)) entries.push([name, ids]);

// Only treat "left"/"right" as a side when both versions exist (so "right atrium" stays as it is).
const stripped = (n) => n.replace(SIDE, '').replace(/\s+/g, ' ').trim();
const sideOf = (n) => (n.match(SIDE)?.[1] || '').toLowerCase();
const seen = new Map();
for (const [n] of entries) {
  const s = sideOf(n);
  if (!s) continue;
  const k = stripped(n).toLowerCase();
  seen.set(k, (seen.get(k) || new Set()).add(s));
}
const vocab = {}; // name -> { left: [], right: [], any: [] }
for (const [n, ids] of entries) {
  const s = sideOf(n);
  const paired = s && seen.get(stripped(n).toLowerCase())?.size === 2;
  let key = paired ? stripped(n) : n;
  key = key[0].toUpperCase() + key.slice(1);
  const v = (vocab[key] ||= { left: [], right: [], any: [] });
  (paired ? v[s] : v.any).push(...ids);
}
for (const v of Object.values(vocab)) for (const k of ['left', 'right', 'any']) v[k] = [...new Set(v[k])];

fs.writeFileSync('public/models/vocab.json', JSON.stringify(vocab));
const names = Object.keys(vocab).sort((a, b) => a.localeCompare(b));
fs.writeFileSync('api/_vocab.js',
  '// Generated by tools/build_vocab.mjs - the structures the 3D model has.\n'
  + `export const STRUCTURES = ${JSON.stringify(names)};\n`);
console.log(names.length, 'structures,', names.join('\n').length, 'characters');
